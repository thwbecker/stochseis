"""Event-driven simulation.

Nucleations are points in time and space generated by a stationary
background Poisson process plus ETAS triggering.  Every nucleation is a
rupture whose area is governed by the same scale-free size hazard,
starting from the area A_min at which a rupture has magnitude mag_min
for the stress drop drawn for the event.  With probability
(A_min / A_patch)^b the rupture reaches the patch size and is grown on
the patch graph (a *fault event*, kind 1); otherwise it stops below one
patch (a *sub-patch event*, kind 0), its area is drawn from the hazard
within [A_min, A_patch), its moment follows the crack law
M0 ~ A^(3/2) of the one-patch solution, and the equivalent slip is
debited on the nucleation patch.  Magnitudes are therefore continuous
across the patch size and the frequency-magnitude distribution is
Gutenberg-Richter by construction below width saturation.

The nucleation rate is not a free parameter: a pilot ensemble of
nucleations (sub-patch and grown, without state-dependent arrest) gives
the expected moment per nucleation, and the rate is chosen so that the
expected release matches the tectonic moment rate sum(mu A v).

Rate feedback: nucleations that fall into the shadow of a recent rupture
are arrested at one patch, so the mean moment per nucleation is lower
than in the pilot calibration and, with a strictly fixed rate, the deficit
would grow without bound.  With ``rate_feedback`` the background
nucleation rate is multiplied by the spatially uniform factor
g(t) = <deficit>(t) / delta_ref, which makes the long-term balance a
stable fixed point without changing where events nucleate.  Triggered
events are not modulated, so aftershock sequences continue after large
events even though the background is quiet.  g is applied by thinning:
background candidates are generated with a bound G >= g and accepted
with probability g/G at their own time.

Kinematics: each rupture is assigned a rupture speed (sub-Rayleigh, or
supershear with a small probability) and every patch an onset time equal
to its graph distance from the nucleation point divided by that speed.
Offspring delays are counted from the onset time of the parent patch
they are drawn from, so no triggering precedes the arrival of the
rupture front.

Events are processed in time order from a heap so that each rupture sees
the fault state at its own origin time, which couples the aftershock
cascade to the budget.
"""

from __future__ import annotations

import heapq
import time

import numpy as np
from scipy.stats import norm

from . import etas
from .catalog import EVENT_DTYPE, Catalog, moment_magnitude
from .geometry import Fault, planar_fault
from .params import Params
from .randomfield import gaussian_field, mai_beroza_correlation_lengths
from .rupture import grow_rupture
from .slip import build_slip
from .state import FaultState
from .stiffness import implied_mean_slip

SECONDS_PER_YEAR = 365.25 * 86400.0


class Simulation:
    def __init__(self, params: Params, fault: Fault | None = None):
        self.p = params
        self.fault = fault if fault is not None else planar_fault(params)
        self.rng = np.random.default_rng(params.seed)
        f = self.fault
        p = params
        self.w_eff = f.width * (2.0 if f.reaches_surface else 1.0)
        self.dsig_med = p.stress_drop_mpa * 1e6
        self.alpha = p.alpha_eff
        self.c_yr = p.omori_c_days / etas.DAYS_PER_YEAR
        self.d_m = p.spatial_d_km * 1e3
        self.mu_ref = float(np.mean(f.mu))
        self.vs = p.vs_km_s * 1e3
        self.meta = {}
        self._setup()

    # ------------------------------------------------------------------
    def g_rate(self, t):
        """Global nucleation-rate factor <deficit>(t) / delta_ref (1 without feedback)."""
        if not self.p.rate_feedback:
            return 1.0
        return max(self.state.mean_deficit(t), 0.0) / self.delta_ref

    def draw_stress_drop(self):
        return self.dsig_med * np.exp(self.p.stress_drop_ln_sigma * self.rng.standard_normal())

    def draw_rupture_speed(self):
        p = self.p
        if self.rng.random() < p.supershear_prob:
            return p.supershear_speed_frac * self.vs
        return p.rupture_speed_frac * self.vs

    def subpatch_fraction(self, dsig):
        """Probability that a rupture with stress drop dsig stays below one patch."""
        m_patch = self.m_patch + (2.0 / 3.0) * np.log10(dsig / self.dsig_med)
        dm = m_patch - self.p.mag_min
        if dm <= 0:
            return 0.0, 1.0
        a_ratio = 10.0 ** (-dm)              # A_min / A_patch (M0 ~ A^1.5)
        return 1.0 - a_ratio ** self.p.b_value, a_ratio

    def draw_subpatch(self, dsig, i0):
        """Area ratio, moment and equivalent patch slip of a sub-patch rupture."""
        p_sub, a_ratio = self.subpatch_fraction(dsig)
        b = self.p.b_value
        # survival (A_min/A)^b truncated at A_patch: A/A_min = (1 - u (1 - a_ratio^b))^(-1/b)
        u = self.rng.random()
        a_over_min = (1.0 - u * (1.0 - a_ratio ** b)) ** (-1.0 / b)
        a_frac = min(a_ratio * a_over_min, 1.0)          # A / A_patch
        f = self.fault
        m0 = self.m0_patch * (dsig / self.dsig_med) * a_frac ** 1.5 * (f.area[i0] * f.mu[i0]) / self.mu_a_ref
        slip_equiv = m0 / (f.mu[i0] * f.area[i0])
        return a_frac, m0, slip_equiv

    def open_connections(self):
        f = self.fault
        if f.n_conn == 0:
            return None
        p_open = np.clip(1.0 - f.conn_gap / f.jump_max, 0.0, 1.0)
        return self.rng.random(f.n_conn) < p_open

    def state_values(self, t, idx):
        if self.p.state_measure == "stress" and self.state.with_stress:
            return self.state.stress(t, idx)
        return self.state.deficit(t, idx)

    # ------------------------------------------------------------------
    def _single_patch_moment(self):
        """Moment of a one-patch rupture at the median stress drop."""
        f = self.fault
        i0 = int(np.argmin((f.col - f.ns // 2) ** 2 + (f.row - f.nz // 2) ** 2))
        slip, _ = build_slip(f, np.array([i0]), np.ones(1), self.dsig_med,
                             np.random.default_rng(0), self.p, diagnostics=False)
        return float(f.mu[i0] * f.area[i0] * slip[0])

    def _grow_and_slip(self, i0, t, dsig, use_state=True, diagnostics=False):
        f = self.fault
        p = self.p if use_state else self.p.replace(arrest_scale=0.0)
        graph = f.graph(self.open_connections())
        if use_state:
            sfn = lambda ii: self.state_values(t, ii)  # noqa: E731
        else:
            sfn = lambda ii: np.ones(len(ii))  # noqa: E731
        idx, dist, code, rho, scale = grow_rupture(f, graph, i0, sfn, dsig, self.rng, p, self.w_eff,
                                                   self.m0_table)
        cond = sfn(idx)
        slip, info = build_slip(f, idx, cond, dsig, self.rng, p, diagnostics=diagnostics)
        if not getattr(self, "_no_scale", False):
            slip = slip * scale                  # continuous stopping size within the last increment
        else:
            scale = 1.0
        info["cap"] = 1.0
        if use_state and p.cap_by_deficit:
            # an event cannot release more slip, on average, than the deficit available on its
            # rupture; roughness and conditioning still redistribute it (local overshoot allowed)
            dbar = float(np.mean(np.maximum(self.state.deficit(t, idx), 0.0)))
            cap = min(1.0, dbar / max(float(np.mean(slip)), 1e-12))
            cap = max(cap, 1e-3)
            slip = slip * cap
            info["cap"] = cap
        info["area"] = float(f.area[idx].sum() * scale ** (2.0 / 3.0))
        info["npatch"] = len(idx)
        return idx, dist, slip, info, code, rho

    def _pilot(self, n=None, grown_only=False):
        """Moment per nucleation (sub-patch and grown) without state-dependent arrest.

        Returns (m0, kind, npatch, dsig) arrays.
        """
        f = self.fault
        n = self.p.pilot_events if n is None else n
        m0 = np.empty(n)
        kind = np.zeros(n, int)
        npatch = np.zeros(n, int)
        dsigs = np.empty(n)
        for k in range(n):
            i0 = int(self.rng.integers(f.n))
            dsig = self.draw_stress_drop()
            dsigs[k] = dsig
            p_sub, _ = self.subpatch_fraction(dsig)
            if (not grown_only) and self.rng.random() < p_sub:
                m0[k] = self.draw_subpatch(dsig, i0)[1]
            else:
                idx, dist, slip, info, code, rho = self._grow_and_slip(i0, 0.0, dsig, use_state=False)
                m0[k] = np.sum(f.mu[idx] * f.area[idx] * slip)
                kind[k] = 1
                npatch[k] = len(idx)
        return m0, kind, npatch, dsigs

    def _build_m0_table(self, k_max=1000, n=3000):
        """Realised moment versus patch count at unit stress-drop ratio.

        Grown pilot ruptures (continuous-size scaling switched off) give the
        ratio r = M0 / M0_analytic(A) of the discretised crack solutions to
        the analytic crack law.  r is about 1.7 for one patch (a one-cell
        boxcar is not a resolved crack) and tends to one for large,
        well-resolved ruptures.  The table is M0_analytic(k) r(k) with r
        taken exactly for k <= 8 and from medians in logarithmic bins of k
        above, interpolated in log k and held constant beyond the last bin
        with at least five samples.
        """
        self.m0_table = None
        self._no_scale = True
        m0, kind, npatch, dsigs = self._pilot(n=n, grown_only=True)
        self._no_scale = False
        f = self.fault
        a_p = float(np.mean(f.area))
        mu = self.mu_ref

        def m0_an(k):
            a = k * a_p
            return mu * a * implied_mean_slip(a, self.w_eff, self.dsig_med, mu)

        m0n = m0 / (dsigs / self.dsig_med)
        ratio = m0n / np.array([m0_an(k) for k in npatch])
        ks, rs = [], []
        for k in range(1, 9):
            sel = npatch == k
            if sel.sum() >= 5:
                ks.append(k)
                rs.append(np.median(ratio[sel]))
        edges = np.unique(np.round(np.logspace(np.log10(9), np.log10(k_max), 20)).astype(int))
        for lo, hi in zip(edges[:-1], edges[1:]):
            sel = (npatch >= lo) & (npatch < hi)
            if sel.sum() >= 5:
                ks.append(np.sqrt(lo * hi))
                rs.append(np.median(ratio[sel]))
        if len(ks) < 2:
            return None
        ks = np.array(ks, float)
        rs = np.array(rs, float)
        kk = np.arange(1, k_max + 1, dtype=float)
        r_k = np.exp(np.interp(np.log(kk), np.log(ks), np.log(rs)))
        table = np.array([m0_an(k) for k in range(1, k_max + 1)]) * r_k
        table = np.maximum.accumulate(table)
        self.m0_ratio_bins = (ks, rs)
        return table

    def _setup(self):
        p, f = self.p, self.fault
        t0 = time.time()
        self.m0_patch = self._single_patch_moment()
        self.m_patch = moment_magnitude(self.m0_patch)
        i_ref = int(np.argmin((f.col - f.ns // 2) ** 2 + (f.row - f.nz // 2) ** 2))
        self.mu_a_ref = float(f.mu[i_ref] * f.area[i_ref])
        self.p_fault = 1.0 - self.subpatch_fraction(self.dsig_med)[0]
        # initial deficit: smooth random field, marginally uniform in [0, D_big]
        d_big = implied_mean_slip(f.total_area, self.w_eff, self.dsig_med, self.mu_ref)
        deficit0 = np.zeros(f.n)
        if p.initial_deficit == "random":
            ax, az = mai_beroza_correlation_lengths(f.ns * f.dx, f.nz * f.dx)
            g = gaussian_field(f.ns, f.nz, f.dx, ax, az, p.hurst, self.rng)
            deficit0 = d_big * norm.cdf(g[f.col, f.row])
        self.state = FaultState(f, deficit0,
                                with_stress=(p.state_measure == "stress" or p.track_stress))
        self.delta_ref = 0.5 * d_big
        self.m0_table = self._build_m0_table() if p.stop_measure == "moment" else None
        pilot_m0, pilot_kind, _, _ = self._pilot()
        pilot_mag = moment_magnitude(pilot_m0)
        budget = f.moment_rate
        if p.nucleation_rate_per_km2_yr > 0:
            nu_tot = p.nucleation_rate_per_km2_yr * f.area.mean() / 1e6 / self.p_fault
        else:
            nu_tot = budget / (f.n * pilot_m0.mean()) * p.budget_scale
        self.nu_tot = nu_tot                         # all nucleations per patch per yr
        self.nu_fault = nu_tot * self.p_fault        # grown ruptures per patch per yr
        n_br = p.branching_ratio if p.etas else 0.0
        self.bg_rate = self.nu_tot * f.n * (1.0 - n_br)   # background rate, whole fault
        if p.etas:
            expectation = float(np.mean(10.0 ** (self.alpha * (pilot_mag - p.mag_min))))
            self.K0 = p.branching_ratio / expectation
        else:
            self.K0 = 0.0
        self.meta.update(dict(
            m0_patch=self.m0_patch, m_patch=self.m_patch, p_fault=self.p_fault,
            nu_fault_per_patch_yr=self.nu_fault, nu_total_per_patch_yr=self.nu_tot,
            background_rate_yr=self.bg_rate, K0=self.K0, moment_rate=budget,
            pilot_mean_m0=float(pilot_m0.mean()), pilot_max_mag=float(pilot_mag.max()),
            pilot_mean_mag=float(pilot_mag.mean()), pilot_fault_fraction=float(pilot_kind.mean()),
            m0_table_length=0 if self.m0_table is None else len(self.m0_table),
            m0_ratio_one_patch=float(self.m0_ratio_bins[1][0]) if self.m0_table is not None else np.nan,
            m0_ratio_last=float(self.m0_ratio_bins[1][-1]) if self.m0_table is not None else np.nan,
            d_big=d_big, delta_ref=self.delta_ref,
            expected_fault_events=self.nu_fault * f.n * p.duration_yr,
            w_eff=self.w_eff, setup_seconds=time.time() - t0))
        if p.verbose:
            print("setup:", {k: (round(v, 4) if isinstance(v, float) else v)
                             for k, v in self.meta.items()})

    # ------------------------------------------------------------------
    def run(self) -> Catalog:
        p, f, rng = self.p, self.fault, self.rng
        T = p.duration_yr
        t0 = time.time()
        heap = []
        seq = 0
        # heap entries: (t, seq, patch, parent, generation, is_background, G)
        G0 = max(1.0, 1.5 * self.g_rate(0.0))
        heapq.heappush(heap, (rng.exponential(1.0 / (self.bg_rate * G0)), seq,
                              int(rng.integers(f.n)), -1, 0, True, G0))
        n_candidates = 0
        events = []
        slip_ptr = [0]
        slip_idx = []
        slip_val = []
        slip_event = []
        n_store = 0
        mu_a = f.mu * f.area
        log_every = max(1, int(T / 20))
        next_log = log_every
        stress_log = []
        while heap:
            t, _, i0, parent, gen, is_bg, G = heapq.heappop(heap)
            if t > T:
                break
            g_now = self.g_rate(t)
            if is_bg:
                seq += 1
                Gn = max(1.0, 1.5 * g_now)
                heapq.heappush(heap, (t + rng.exponential(1.0 / (self.bg_rate * Gn)), seq,
                                      int(rng.integers(f.n)), -1, 0, True, Gn))
            n_candidates += 1
            # thinning of background candidates for the rate feedback
            if is_bg and p.rate_feedback and g_now < G and rng.random() * G >= g_now:
                continue
            eid = len(events)
            dsig = self.draw_stress_drop()
            p_sub, _ = self.subpatch_fraction(dsig)
            if rng.random() >= p_sub:
                store = False
                idx, dist, slip, info, code, rho = self._grow_and_slip(i0, t, dsig)
                self.state.apply_event(idx, slip)
                m0 = float(np.sum(mu_a[idx] * slip))
                mag = moment_magnitude(m0)
                w = slip * f.area[idx]
                w /= w.sum()
                cs = float(np.dot(w, f.s[idx]))
                czd = float(np.dot(w, f.zd[idx]))
                cx = float(np.dot(w, f.x[idx]))
                cy = float(np.dot(w, f.y[idx]))
                cz = float(np.dot(w, f.z[idx]))
                vr = self.draw_rupture_speed()
                onset = dist / vr                          # seconds after origin
                duration = float(onset.max())
                store = mag >= p.store_slip_min_mag
                events.append((t, mag, m0, 1, i0, cs, czd, cx, cy, cz, info["L"], info["W"],
                               info["area"], len(idx), info["dmean"], info["dmax"],
                               dsig, duration, vr, int(info["surface"]), code, rho, parent, gen,
                               int(store)))
                if store:
                    slip_idx.append(idx)
                    slip_val.append(slip)
                    slip_event.append(eid)
                    n_store += len(idx)
                    slip_ptr.append(n_store)
                parent_patches = idx
                parent_onset = onset / SECONDS_PER_YEAR
                parent_w = slip / slip.sum()
            else:
                a_frac, m0, slip_eq = self.draw_subpatch(dsig, i0)
                if p.cap_by_deficit:
                    cap = max(min(1.0, max(self.state.deficit(t, i0), 0.0) / slip_eq), 1e-3)
                    m0 *= cap
                    slip_eq *= cap
                mag = moment_magnitude(m0)
                self.state.apply_event(np.array([i0]), np.array([slip_eq]))
                side = f.dx * np.sqrt(a_frac)
                events.append((t, mag, m0, 0, i0, f.s[i0], f.zd[i0], f.x[i0], f.y[i0], f.z[i0],
                               side, side, float(f.area[i0] * a_frac), 1, slip_eq, slip_eq,
                               dsig, side / self.draw_rupture_speed(), np.nan, 0, -1, np.nan,
                               parent, gen, 0))
                parent_patches = None
            # offspring
            if p.etas:
                Gc = 1.0
                n_off = rng.poisson(self.K0 * 10.0 ** (self.alpha * (mag - p.mag_min)))
                if n_off > 0:
                    delay = etas.omori_times(n_off, self.c_yr, p.omori_p, rng)
                    if parent_patches is None:
                        src = np.full(n_off, i0)
                        tc = t + delay
                    else:
                        j = rng.choice(len(parent_patches), size=n_off, p=parent_w)
                        src = parent_patches[j]
                        tc = t + parent_onset[j] + delay
                    keep = tc <= T
                    n_keep = int(keep.sum())
                    if n_keep > 0:
                        tc = tc[keep]
                        src = src[keep]
                        ds, dz = etas.spatial_offsets(n_keep, self.d_m, p.spatial_q, rng)
                        child = f.nearest_patch(f.s[src] + ds, f.zd[src] + dz)
                        for k in range(n_keep):
                            seq += 1
                            heapq.heappush(heap, (float(tc[k]), seq, int(child[k]), eid, gen + 1, False, Gc))
            if t >= next_log:
                if self.state.with_stress:
                    stress_log.append((t,) + self.state.stress_heterogeneity(t))
                if p.verbose:
                    print(f"t = {t:9.1f} yr  events = {len(events):8d}  heap = {len(heap):7d}  g = {g_now:.2f}  elapsed = {time.time() - t0:7.1f} s", flush=True)
                next_log += log_every
        ev = np.array(events, dtype=EVENT_DTYPE)
        if n_store:
            slip_idx = np.concatenate(slip_idx)
            slip_val = np.concatenate(slip_val)
        else:
            slip_idx = np.zeros(0, int)
            slip_val = np.zeros(0)
        n_ev = len(ev)
        meta = dict(self.meta)
        meta.update(dict(
            n_events=n_ev,
            n_fault_events=int(np.sum(ev["kind"] == 1)) if n_ev else 0,
            realised_branching_ratio=float(np.mean(ev["parent"] >= 0)) if n_ev else 0.0,
            released_moment=float(np.sum(ev["m0"])) if n_ev else 0.0,
            released_moment_fault=float(np.sum(ev["m0"][ev["kind"] == 1])) if n_ev else 0.0,
            loaded_moment=f.moment_rate * T,
            n_candidates=n_candidates,
            final_mean_deficit=self.state.mean_deficit(T),
            final_g=self.g_rate(T),
            run_seconds=time.time() - t0))
        if self.state.with_stress:
            m, s, fneg = self.state.stress_heterogeneity(T)
            meta.update(final_stress_mean_mpa=m / 1e6, final_stress_std_mpa=s / 1e6,
                        final_stress_frac_negative=fneg)
            if stress_log:
                sl = np.array(stress_log)
                meta.update(mean_stress_mpa=float(sl[:, 1].mean() / 1e6),
                            mean_stress_std_mpa=float(sl[:, 2].mean() / 1e6))
        meta["moment_closure"] = meta["released_moment"] / meta["loaded_moment"]
        if p.verbose:
            print(f"done: {n_ev} events in {meta['run_seconds']:.1f} s, "
                  f"moment closure {meta['moment_closure']:.3f}")
        return Catalog(ev, f, p, meta, np.array(slip_ptr), slip_idx, slip_val,
                       np.array(slip_event, int), self.state.released.copy(),
                       self.state.deficit0.copy())


def run(params: Params, fault: Fault | None = None) -> Catalog:
    """Convenience wrapper: build, calibrate and run one simulation."""
    return Simulation(params, fault).run()
